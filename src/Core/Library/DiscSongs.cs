    /// <summary>True for disc file names like "X04", "Z01", "H06" (one capital letter + two digits), as used in tracklist paths.</summary>
    public static bool IsDiscFileName(string path) =>
        path.Length == 3 && path[0] is >= 'A' and <= 'Z' && char.IsAsciiDigit(path[1]) && char.IsAsciiDigit(path[2]);
